"""Write results/SUMMARY.md. Every number is read from results/*.json; only the prose is fixed."""
import json

import numpy as np

from common import DATA, RESULTS


def J(name):
    return json.load(open(RESULTS / name, encoding="utf-8"))


def main():
    man = json.load(open(DATA / "manifest.json"))
    meta = J("path_outputs_meta.json")
    ocr, tx, vi = J("ocr_cost.json"), J("index_cost_text.json"), J("index_cost_visual.json")
    lb, ev, es = J("labels.json"), J("eval_main.json"), J("escalation.json")
    lt, ix, rc, bj = J("load_test.json"), J("index_scaling.json"), J("router_cost.json"), J("batching.json")
    hw = meta["hardware"]
    g = hw["gpus"][0]
    a = ev["aggregate"]

    rows = [json.loads(l) for l in open(RESULTS / "path_outputs.jsonl", encoding="utf-8")]
    def path_stat(p, k, f=np.mean):
        return float(f([r[k] for r in rows if r["path"] == p]))
    by = {}
    for r in rows:
        by.setdefault(r["qid"], []).append(r["anls"])
    all_fail = float(np.mean([max(v) == 0 for v in by.values()]))

    def pol(n, k="anls"):
        return f"{a[n][k]['mean']:.3f} ± {a[n][k]['std']:.3f}"

    def esc(sig, mode, tau):
        vs = [s["results"][sig][mode][tau] for s in es["per_seed"]]
        return {k: float(np.mean([v[k] for v in vs])) for k in vs[0]}

    def sweep(n, lam):
        return {k: float(np.mean([s["lambda_sweep"][lam][n][k] for s in ev["per_seed"]])) for k in ("anls", "gpu_s")}

    kw = lb["keyword_rule_vs_outcome"]["keyword_submitted"]
    p_vis = [s["tests_vs_cavr"]["always_visual"]["mcnemar_em"]["p_value"] for s in ev["per_seed"]]
    p_hyb = [s["tests_vs_cavr"]["always_hybrid"]["mcnemar_em"]["p_value"] for s in ev["per_seed"]]
    P = lt["policies"]
    gp = lambda n, load="100": P[n]["gpus_needed"]["2.0"][load]
    e_best = esc("colpali_margin", "reroute", "0.7")
    rf05, hyb = sweep("cavr_rf", "0.05"), a["always_hybrid"]
    s100 = ix["scaling"]["100000"]
    pr = ix["pooling_recall_at1"]
    bq = {p: max(v.values(), key=lambda x: x["queries_per_s"] if "note" not in x else 0) for p, v in bj["paths"].items()}

    # Content-aware router (Phase 1)
    ce_sum, ce_lc, ce_cost = J("router_ce/summary.json"), J("router_ce/learning_curve.json"), J("router_ce_cost.json")
    ce = a["cavr_ce_valsel"]
    ce_seeds = [x for x in ev["per_seed"] if "cavr_ce_valsel" in x["policies"]]
    ce_p_h = [x["tests_cavr_ce_valsel"]["always_hybrid"]["mcnemar_em"]["p_value"] for x in ce_seeds]
    ce_p_v = [x["tests_cavr_ce_valsel"]["always_visual"]["mcnemar_em"]["p_value"] for x in ce_seeds]
    ce_ci_h = [x["tests_cavr_ce_valsel"]["always_hybrid"]["paired_boot_anls"]["ci95"] for x in ce_seeds]
    ce_save = [100 * (1 - x["policies"]["cavr_ce_valsel"]["gpu_s"] / x["policies"]["always_hybrid"]["gpu_s"]) for x in ce_seeds]
    ce_auc = float(np.mean([x["ce_full"]["auc_mean"] for x in ce_sum["seeds"]]))
    gbm_auc = float(np.mean([x["gbm_tab"]["auc_mean"] for x in ce_sum["seeds"]]))
    lc = {f: float(np.mean([r["ce_auc"] for r in ce_lc["runs"] if r["frac"] == f])) for f in ce_lc["fracs"]}

    def esc_ce(sig, mode, tau):
        vs = [x["results_ce"][sig][mode][tau] if sig != "none" else x["results_ce"]["none"] for x in es["per_seed"]
              if "results_ce" in x]
        return {k: float(np.mean([v[k] for v in vs])) for k in vs[0]}
    ce_none, ce_esc = esc_ce("none", None, None), esc_ce("colpali_margin", "reroute", "0.5")

    md = f"""# CAVR revision: results summary

Generated by `make_summary.py` from `results/*.json`. No number below was typed by hand.

## Setup

- **Hardware:** 1× {g['name']} ({g['memory_gb']} GB, power limit {g['power_limit_w']:.0f} W), driver {hw.get('driver')}, CUDA {hw.get('cuda_runtime')}, {hw['cpu_threads']} CPU threads, {hw['ram_gb']} GB RAM, {hw['os']}.
- **Data:** DocVQA + InfographicVQA validation, {man['natural']['queries']} questions over {man['pages']['total']} unique pages (`data/manifest.json`).
- **Paths:** one generator ({meta['model']}, greedy) for all three:
  - text: BM25 top-{meta['k_text']} pages of docTR OCR text
  - visual: ColPali v1.3 top-1 page image, ≤ {meta['max_pixels'] // 784} visual tokens
  - hybrid: both
- **Metrics:** ANLS, exact match, and costs measured on this GPU: GPU-seconds, NVML energy, wall latency.
- **Evaluation:** 5 seeds; each seed is a new page-grouped 60/20/20 split, so no page appears in two splits.

## What changed vs the submitted paper

| | Submitted paper | Revision |
|---|---|---|
| Labels | Keyword rule over the question text | Outcome labels: the best path by measured ANLS − λ·cost, plus "cheapest path with ANLS ≥ 0.5" |
| Agreement of the old labels with outcomes | — | {100 * kw['agreement_with_utility_label']:.1f}% agreement, **Cohen's κ = {kw['kappa_with_utility_label']:.3f}** (none beyond chance); the rule sends {100 * kw['distribution'].get('text', 0) / lb['n_queries']:.0f}% of queries to text |
| Cost | Router latency × A100 rate, and word count × GPT-3.5 price | Measured GPU-seconds and energy per query on one RTX 4090 |
| Quality | Router classification accuracy (85.4% in `main_results.tex`, 86.2% in the text) against keyword labels | End-to-end answer quality (ANLS, EM) of the answer each routing policy produces |
| Retrieval / generation | Not run | Run for every query on every path, cached in `results/path_outputs.jsonl` |

## Bottom line: the claim the evidence supports

- **Content-aware routing (CAVR-CE) reaches near-hybrid answer quality with about {np.mean(ce_save):.0f}% less GPU compute.**
  - Quality: ANLS {ce['anls']['mean']:.3f} vs {hyb['anls']['mean']:.3f} for always-hybrid.
  - Compute: {ce['gpu_s']['mean']:.3f} vs {hyb['gpu_s']['mean']:.3f} GPU-s per query, including ColPali and the router's own overhead.
  - Choice of λ: picked on validation data.
- **Significance against always-hybrid:** the exact-match difference is not significant on {sum(p > 0.05 for p in ce_p_h)} of {len(ce_p_h)} seeds. The ANLS 95% CI excludes zero on {sum(ci[1] < 0 for ci in ce_ci_h)} of {len(ce_ci_h)} seeds.
- **Significance against always-visual:** CAVR-CE is significantly better on {sum(p < 0.05 for p in ce_p_v)} of {len(ce_p_v)} seeds.
- **At serving scale** (100 QPS at p95 ≤ 2 s): CAVR-CE needs {gp('cavr_ce_valsel')} GPUs against {gp('always_hybrid')} for always-hybrid.
- **What is not supported:**
  - the submitted 86.2% routing accuracy, because its labels don't match outcomes;
  - $0.00019 per query, because it was never measured;
  - the premise that the text path is cheap with a shared generator.
- **Open problem:** a per-query oracle shows much larger headroom (ANLS {a['oracle']['anls']['mean']:.3f} at {a['oracle']['gpu_s']['mean']:.3f} GPU-s). Predicting per-query success is what limits routing.

## Headline numbers

### Paths (all {lb['n_queries']} queries)

| Path | ANLS | EM | GPU-s/query | Energy/query (J) | p95 latency (s) |
|---|---|---|---|---|---|
""" + "\n".join(
        f"| {p} | {path_stat(p, 'anls'):.3f} | {path_stat(p, 'em'):.3f} | {path_stat(p, 'gpu_seconds'):.3f} | "
        f"{path_stat(p, 'energy_j'):.0f} | {float(np.percentile([r['wall_s'] for r in rows if r['path'] == p], 95)):.2f} |"
        for p in ("text", "visual", "hybrid")) + f"""

- **Oracle:** picking the best path per query would give ANLS {float(np.mean([max(v) for v in by.values()])):.3f}.
- **{100 * all_fail:.1f}% of queries fail on every path**, almost always because neither retriever finds the gold page. Page recall@1 is {tx['recall']['@1']:.3f} for BM25 and {vi['recall']['@1']:.3f} for ColPali. No router can recover these queries.
- **With a shared local generator, the text path is not cheap.** It costs {path_stat('text', 'gpu_seconds'):.2f} GPU-s against {path_stat('visual', 'gpu_seconds'):.2f} for visual, because OCR text produces as many input tokens as the page image. It is also much less accurate. The real cost differences are hybrid vs single path (about 2×) and the size of the ColPali index at scale.

### Routing policies (held-out test pages, mean ± std over {ev['n_seeds']} seeds, λ = {ev['lambda_default']})

| Policy | ANLS | GPU-s/query |
|---|---|---|
| Always text | {pol('always_text')} | {pol('always_text', 'gpu_s')} |
| Always visual | {pol('always_visual')} | {pol('always_visual', 'gpu_s')} |
| Always hybrid | {pol('always_hybrid')} | {pol('always_hybrid', 'gpu_s')} |
| Keyword rule (submitted) | {pol('keyword_submitted')} | {pol('keyword_submitted', 'gpu_s')} |
| Logistic regression | {pol('logreg')} | {pol('logreg', 'gpu_s')} |
| kNN quality | {pol('knn')} | {pol('knn', 'gpu_s')} |
| CAVR | {pol('cavr')} | {pol('cavr', 'gpu_s')} |
| CAVR + BM25 + ColPali scores | {pol('cavr_rf')} | {pol('cavr_rf', 'gpu_s')} |
| CAVR-CE (content-aware), λ = {ev['lambda_default']} | {pol('cavr_ce')} | {pol('cavr_ce', 'gpu_s')} |
| CAVR-CE, λ chosen on val | {pol('cavr_ce_valsel')} | {pol('cavr_ce_valsel', 'gpu_s')} |
| Random routing at CAVR's budget | {a['random_equal_budget']['anls']['mean']:.3f} | {a['random_equal_budget']['gpu_s']['mean']:.3f} |
| Per-query oracle | {pol('oracle')} | {pol('oracle', 'gpu_s')} |

Router overhead (mpnet + MLP, batch 1) is included for the learned policies: {1000 * rc['cuda']['batch1_p50_s']:.1f} ms and {rc['per_query_batch1']['energy_j']:.2f} J per query.

**How to read this honestly:**
- **Default λ.** CAVR sends most queries to visual and is statistically the same as always-visual (McNemar p per seed: {', '.join(f'{p:.2g}' for p in p_vis)}). It is significantly worse than always-hybrid on EM (p: {', '.join(f'{p:.2g}' for p in p_hyb)}), at {100 * (1 - a['cavr']['gpu_s']['mean'] / hyb['gpu_s']['mean']):.0f}% lower GPU cost.
- **Lower λ.** CAVR + retrieval scores at λ = 0.05 reaches ANLS {rf05['anls']:.3f} at {rf05['gpu_s']:.3f} GPU-s, against always-hybrid's {hyb['anls']['mean']:.3f} at {hyb['gpu_s']['mean']:.3f}. That is {100 * (1 - rf05['gpu_s'] / hyb['gpu_s']['mean']):.0f}% less compute at a change of {rf05['anls'] - hyb['anls']['mean']:+.3f} ANLS.
- **Headroom.** The gap to the oracle ({a['oracle']['anls']['mean']:.3f} at {a['oracle']['gpu_s']['mean']:.3f} GPU-s) is large. Question text and retrieval scores predict only part of it.

### Content-aware router (CAVR-CE)

CAVR-CE is the Phase 1 router. Phase 0 probes are in `results/phase0/VERDICT.md`.

**How it works**
- An mpnet cross-encoder reads the question plus the best-matching OCR passages from BM25's pages and ColPali's top page.
- It also takes tabular inputs: retrieval scores, content-match features and ColPali per-token match statistics.
- It predicts each path's ANLS. λ is chosen per seed on validation data as the cheapest setting within 0.005 ANLS of hybrid.

**Cost and accuracy**
- Router overhead: {1000 * ce_cost['per_query_batch1']['latency_s']:.1f} ms and {ce_cost['per_query_batch1']['energy_j']:.2f} J per query, plus ColPali for every query. Both are included in all numbers.
- Success-prediction AUC: {ce_auc:.3f}, against {gbm_auc:.3f} for gradient boosting on the same tabular features. The pre-set target was 0.87, so it was missed.
- Learning curve: AUC goes from {lc[0.25]:.3f} at 25% of the training data to {lc[1.0]:.3f} at 100%, about +0.007 per doubling and flattening. More labelled data is unlikely to reach 0.87.

**Results per seed**
- GPU saving vs always-hybrid: {', '.join(f'{v:.0f}%' for v in ce_save)}.
- McNemar p vs hybrid: {', '.join(f'{p:.2g}' for p in ce_p_h)}.
- McNemar p vs visual: {', '.join(f'{p:.2g}' for p in ce_p_v)}.

**Escalation on CAVR-CE** (ColPali margin, τ = 0.5): ANLS {ce_none['anls']:.3f} → {ce_esc['anls']:.3f}, GPU-s {ce_none['gpu_s']:.3f} → {ce_esc['gpu_s']:.3f}, with {100 * ce_esc['escalation_rate']:.0f}% of queries escalated. Escalation trades back part of the saving to close the remaining quality gap. The full τ sweep is in `paper_out/figures/escalation.png`.

### Escalation (step 7, CAVR base, mean over seeds)

- **Best signal:** the ColPali score margin, applied before generation (re-route to hybrid). At τ = 0.7 it gives ANLS {e_best['anls']:.3f} at {e_best['gpu_s']:.3f} GPU-s, p95 {e_best['latency_p95_s']:.2f} s, with {100 * e_best['escalation_rate']:.0f}% of queries escalated.
- **Answer log-prob signals** need the first answer before deciding, so they add latency.
  - Serial: p95 {esc('answer_logprob_min', 'serial', '0.5')['latency_p95_s']:.2f} s.
  - Speculative (hybrid launched alongside the routed path, assuming 2 concurrent workers): p95 falls to {esc('answer_logprob_min', 'speculative', '0.5')['latency_p95_s']:.2f} s, but GPU cost rises to {esc('answer_logprob_min', 'speculative', '0.5')['gpu_s']:.2f} GPU-s.

### HPC / serving (step 8)

**Router**
- Batch-1 latency: {1000 * rc['cuda']['batch1_p50_s']:.1f} ms on the GPU, {1000 * rc['cpu']['batch1_p50_s']:.1f} ms on the CPU.
- Peak throughput: {max(v['queries_per_s'] for v in rc['cuda']['throughput'].values()):,.0f} queries/s at large batch. That is negligible next to generation.

**Batched generation** (HF transformers; best batch size within VRAM)
- text {bq['text']['queries_per_s']:.2f} q/s, visual {bq['visual']['queries_per_s']:.2f} q/s, hybrid {bq['hybrid']['queries_per_s']:.2f} q/s per GPU.

**Load test** (Poisson arrivals, dynamic batching, measured service times; seed-1 test split): GPUs needed to hold p95 ≤ 2 s at 100 QPS.

| Policy | GPUs |
|---|---|
| Always hybrid | {gp('always_hybrid')} |
| CAVR (λ = 0.1) | {gp('cavr')} |
| Always visual | {gp('always_visual')} |
| CAVR + retrieval scores (λ = 0.05) | {gp('cavr_rf@0.05')} |
| CAVR-CE (λ chosen on val) | {gp('cavr_ce_valsel')} |
| Oracle | {gp('oracle')} |

**ColPali index at 100k pages** ({s100['index_gb_bf16']:.1f} GB in bf16) does not fit on one 24 GB GPU:
- Streamed from host RAM: {1000 * s100['cpu_stream']['p50_s']:.0f} ms per query.
- 2×2 pooled, on the GPU: {s100['index_gb_pooled2x2']:.1f} GB and {1000 * s100['gpu_pooled2x2']['p50_s']:.1f} ms per query, but R@1 on the real corpus drops from {pr['full']:.3f} to {pr['pooled2x2']:.3f}.
- Sharded over {s100['sharded']['gpus_needed']} GPUs (emulated): {1000 * s100['sharded']['emulated_parallel_p50_s']:.1f} ms per query.
- Building the index takes about {ix['build']['extrapolated_build_hours']['100000']:.1f} GPU-hours at {ix['build']['by_batch'][str(ix['build']['best_batch'])]['pages_per_s']:.1f} pages/s.

## Limitations to state in the paper

- **One consumer GPU (RTX 4090) under Windows WDDM.** Caps on visual tokens and OCR text length keep memory below the point where the driver spills to system RAM. Batch sizes that came near that point are excluded.
- **Generation uses HF transformers `generate`, not a serving engine** (vLLM/TGI), so batching gains are modest. Absolute capacity numbers are therefore pessimistic. The relative comparison between policies is the main result.
- **The load test is a discrete-event simulation** driven by measured per-query service times and measured batching curves, not live traffic.
- **10k–100k-page indexes repeat the real page embeddings.** That is valid for latency and memory, not for retrieval quality at that scale.
- **Multi-GPU sharding is emulated:** shards are timed one after another on one GPU.
- **Speculative-escalation latency assumes two concurrent workers.**
- **Retrieval searches each dataset's own page pool.** DocVQA questions are often generic, so page recall is low and caps every policy (the {100 * all_fail:.0f}% of queries that fail on every path).
"""
    (RESULTS / "SUMMARY.md").write_text(md, encoding="utf-8")
    print(f"wrote {RESULTS / 'SUMMARY.md'}")


if __name__ == "__main__":
    main()
