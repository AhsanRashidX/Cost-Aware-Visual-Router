# ------------------------------------------------------------------ rendering helpers
TOKEN = re.compile(r"(\[AUTHOR ACTION:[^\]]*\])")
TEX_MAP = {"λ": r"$\lambda$", "κ": r"$\kappa$", "τ": r"$\tau$", "≤": r"$\le$", "≥": r"$\ge$", "±": r"$\pm$",
           "×": r"$\times$", "→": r"$\rightarrow$", "−": r"$-$", "–": "--", "—": "---", "α": r"$\alpha$",
           "β": r"$\beta$", "γ": r"$\gamma$", "·": r"$\cdot$", "q̂_p": r"$\hat{q}_p$", "c̄_p": r"$\bar{c}_p$",
           "argmax_p": r"$\arg\max_p$"}


def tex_escape(s):
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("$", r"\$")):
        s = s.replace(a, b)
    s = s.replace(r"q̂\_p", "q̂_p").replace(r"c̄\_p", "c̄_p").replace(r"argmax\_p", "argmax_p")
    for a in sorted(TEX_MAP, key=len, reverse=True):
        s = s.replace(a, TEX_MAP[a])
    s = re.sub(r'"([^"]*)"', r"``\1''", s)
    s = re.sub(r"(?<!\\)\$\$", "", s)   # join neighbouring inline-math pieces
    return s


def tex_inline(s):
    return "".join(r"\textcolor{red}{" + tex_escape(p) + "}" if TOKEN.fullmatch(p) else tex_escape(p)
                   for p in TOKEN.split(s) if p)


def render_tex(V):
    f = lambda s: tex_inline(fill(s, V))
    L = [r"\documentclass[11pt]{article}", r"\usepackage[margin=1in]{geometry}", r"\usepackage[T1]{fontenc}",
         r"\usepackage{lmodern,mathptmx}", r"\usepackage{xcolor,booktabs,tabularx,titlesec}",
         r"\titleformat{\section}{\large\bfseries}{}{0pt}{}", r"\titleformat{\subsection}{\normalsize\bfseries}{}{0pt}{}",
         r"\setlength{\parindent}{0pt}\setlength{\parskip}{0.6em}",
         r"\newcommand{\reviewer}[1]{{\color{blue!55!black}\itshape #1\par}}",
         r"\begin{document}", r"\begin{center}{\Large\bfseries " + TITLE + r"}\\[0.4em]",
         tex_inline(SUBTITLE) + r"\end{center}", r"\textcolor{red}{\small " + tex_escape(DRAFT_NOTE) + "}", ""]
    L += [f(p) + "\n" for p in OPENING]
    L += [r"\section*{Withdrawn or corrected claims}",
          r"\begin{tabularx}{\textwidth}{>{\raggedright\arraybackslash}p{0.27\textwidth}l>{\raggedright\arraybackslash}X}",
          r"\toprule \textbf{Submitted claim} & \textbf{Status} & \textbf{What the revised paper reports} \\ \midrule"]
    L += [f"{f(a)} & {f(b)} & {f(c)} \\\\" for a, b, c in WITHDRAWN]
    L += [r"\bottomrule\end{tabularx}", ""]
    for group, head, comment, resp in COMMENTS:
        if group:
            L.append(r"\section*{" + group + "}")
        L.append(r"\subsection*{" + tex_inline(head) + "}")
        L.append(r"\reviewer{" + f(comment) + "}")
        L.append(r"\textbf{Response.} " + f(resp[0]))
        L += ["\n" + f(p) for p in resp[1:]]
        L.append("")
    L += [f(CLOSING), r"\end{document}", ""]
    return "\n".join(L)


def render_docx(V, path):
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Inches, Pt, RGBColor
    BLUE, RED = RGBColor(0x1F, 0x3A, 0x8A), RGBColor(0xC0, 0x1F, 0x1F)
    doc = Document()
    for s in doc.sections:
        s.left_margin = s.right_margin = s.top_margin = s.bottom_margin = Inches(1)
        p = s.footer.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run()
        for tag, text in (("begin", None), (None, "PAGE"), ("end", None)):
            if tag:
                el = OxmlElement("w:fldChar")
                el.set(qn("w:fldCharType"), tag)
            else:
                el = OxmlElement("w:instrText")
                el.text = text
            r._r.append(el)
    st = doc.styles["Normal"]
    st.font.name, st.font.size = "Times New Roman", Pt(11)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    st.paragraph_format.space_after = Pt(6)

    SUB = re.compile(r"(q̂_p|c̄_p|argmax_p)")

    def runs(par, text, italic=False, color=None, bold=False, size=None):
        for part in TOKEN.split(text):
            if not part:
                continue
            col = RED if TOKEN.fullmatch(part) else color
            for piece in SUB.split(part):
                if not piece:
                    continue
                segs = [(piece[:-2], False), ("p", True)] if SUB.fullmatch(piece) else [(piece, False)]
                for txt, sub in segs:
                    r = par.add_run(txt)
                    r.italic, r.bold = italic, bold
                    r.font.subscript = sub
                    if size:
                        r.font.size = Pt(size)
                    if col is not None:
                        r.font.color.rgb = col

    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    runs(p, TITLE, bold=True, size=16)
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    runs(p, SUBTITLE)
    p = doc.add_paragraph(); runs(p, DRAFT_NOTE, color=RED, size=9.5)
    for para in OPENING:
        p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        runs(p, fill(para, V))

    def heading(text, size):
        p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(10); p.paragraph_format.keep_with_next = True
        runs(p, text, bold=True, size=size)

    heading("Withdrawn or corrected claims", 13)
    t = doc.add_table(rows=1, cols=3)
    t.style = "Light Grid Accent 1"
    for i, h in enumerate(("Submitted claim", "Status", "What the revised paper reports")):
        t.rows[0].cells[i].text = ""
        runs(t.rows[0].cells[i].paragraphs[0], h, bold=True, size=9.5)
    for a, b, c in WITHDRAWN:
        cells = t.add_row().cells
        for cell, txt in zip(cells, (a, b, c)):
            cell.text = ""
            runs(cell.paragraphs[0], fill(txt, V), size=9.5)
    widths = (Inches(1.9), Inches(0.8), Inches(3.8))
    for row in t.rows:
        for cell, w in zip(row.cells, widths):
            cell.width = w
    for group, head, comment, resp in COMMENTS:
        if group:
            heading(group, 13)
        heading(head, 11.5)
        p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        runs(p, fill(comment, V), italic=True, color=BLUE)
        p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        runs(p, "Response. ", bold=True)
        runs(p, fill(resp[0], V))
        for extra in resp[1:]:
            p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            runs(p, fill(extra, V))
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(10); p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    runs(p, CLOSING)
    doc.save(path)


def docx_to_pdf(docx_path, pdf_path):
    import pythoncom
    import win32com.client
    pythoncom.CoInitialize()
    word = win32com.client.DispatchEx("Word.Application")
    word.Visible = False
    try:
        d = word.Documents.Open(str(docx_path), ReadOnly=True)
        d.SaveAs(str(pdf_path), FileFormat=17)   # wdFormatPDF
        d.Close(False)
    finally:
        word.Quit()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    V = extra_values(values())
    (OUT / "response_to_reviewers.tex").write_text(render_tex(V), encoding="utf-8")
    docx_path, pdf_path = OUT / "response_to_reviewers.docx", OUT / "response_to_reviewers.pdf"
    render_docx(V, docx_path)
    docx_to_pdf(docx_path, pdf_path)
    print(f"wrote {OUT / 'response_to_reviewers.tex'}, {docx_path.name}, {pdf_path.name}")


if __name__ == "__main__":
    main()
