"""Copy the generated paper into a self-contained LaTeX package for the authors' own document (copy only).

Writes <out>/ (default D:/CAVR_paper_latex) with text/, tables/, figures/ (only the figures the sections include, as
PDF plus PNG), references.bib, letter/, a sample main.tex (Springer LNCS class, the authors' template) showing the
package list and the \\input order, and CHANGES.md; then zips the folder as <out>_<date>.zip.
Usage: python make_latex_package.py [--out D:/CAVR_paper_latex]
"""
import argparse
import datetime
import re
import shutil
import zipfile
from pathlib import Path

from common import ROOT

SRC = ROOT / "paper_out"
SECTIONS = ["abstract", "introduction", "related", "method", "setup", "results_section", "conclusion"]

MAIN = r"""%% Sample wrapper generated by make_latex_package.py. Copy the \input lines into your own document;
%% the sections need graphicx, booktabs, adjustbox, amsmath and amssymb. figure* floats span both columns in a two-column
%% class and behave like figure in LNCS.
\documentclass[runningheads]{llncs}
\usepackage[T1]{fontenc}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{adjustbox}
\usepackage{amsmath}
\usepackage{amssymb}
\usepackage[hidelinks]{hyperref}

\begin{document}
\title{Cost-Aware Visual Router (CAVR): Dynamic Query Routing for Cost-Efficient Multimodal Retrieval-Augmented Generation}
\titlerunning{Cost-Aware Visual Router (CAVR)}
\author{[AUTHOR ACTION: authors]}
\institute{[AUTHOR ACTION: affiliations]}
\maketitle

%SECTIONS%

\bibliographystyle{splncs04}
\bibliography{references}
\end{document}
"""

