def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="D:/CAVR_paper_latex")
    out = Path(ap.parse_args().out)
    if out.exists():
        shutil.rmtree(out)          # the package is fully regenerated from paper_out
    for d in ("text", "tables", "figures", "letter"):
        (out / d).mkdir(parents=True)
    used_tables, used_figs = set(), set()
    for name in SECTIONS:
        t = (SRC / "text" / f"{name}.tex").read_text(encoding="utf-8")
        used_tables |= set(re.findall(r"\\input\{tables/([^}]+)\}", t))
        used_figs |= set(re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{figures/([^}.]+)\.(?:pdf|png)\}", t))
        shutil.copy2(SRC / "text" / f"{name}.tex", out / "text")
    for t in sorted(used_tables):
        shutil.copy2(SRC / "tables" / f"{t}.tex", out / "tables")
    for f in sorted(used_figs):
        for ext in ("pdf", "png"):
            if (SRC / "figures" / f"{f}.{ext}").exists():
                shutil.copy2(SRC / "figures" / f"{f}.{ext}", out / "figures")
    shutil.copy2(SRC / "references.bib", out)
    for f in (SRC / "letter").iterdir():
        shutil.copy2(f, out / "letter")
    (out / "main.tex").write_text(MAIN.replace("%SECTIONS%", "\n".join(f"\\input{{text/{s}}}" for s in SECTIONS)),
                                  encoding="utf-8")
    (out / "CHANGES.md").write_text(CHANGES, encoding="utf-8")
    zpath = out.parent / f"{out.name}_{datetime.date.today().isoformat()}.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(out.rglob("*")):
            if p.is_file():
                z.write(p, Path(out.name) / p.relative_to(out))
    print(f"{out}: {len(SECTIONS)} sections, {len(used_tables)} tables, {len(used_figs)} figures -> {zpath}")


if __name__ == "__main__":
    main()
