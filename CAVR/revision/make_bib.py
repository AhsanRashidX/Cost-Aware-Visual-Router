"""Write paper_out/references.bib from paper_out/refs_verified.json (offline; no entry is typed by hand).

refs_verified.json holds, per citation key, the record it was verified against: a Crossref record by DOI, a venue
stated by the authors' arXiv comment or the publisher's page (with the arXiv record for authors and title), or the arXiv
preprint itself. Keys cited in paper_out/text/*.tex but missing from the file are reported, not invented.
"""
import json
import re

from common import ROOT

OUT = ROOT / "paper_out"
CROSSREF_TYPES = {"proceedings-article": "inproceedings", "journal-article": "article", "book": "book",
                  "monograph": "book", "posted-content": "misc"}


def esc(s):
    s = str(s).replace("&amp;", "&").replace("®", "")  # drop the registered sign in journal names
    for a, b in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_")):
        s = s.replace(a, b)
    return s


def authors(lst):
    return " and ".join(f"{esc(fam)}, {esc(giv)}" if giv else "{" + esc(fam) + "}" for giv, fam in lst)


def protect(title):
    """Keep acronyms and capitalised model names as written."""
    return " ".join("{" + w + "}" if re.search(r"[A-Z].*[A-Z]|[A-Z].*\d", w) else w for w in esc(title).split())


def entry(key, v):
    f = {}
    if v["kind"] == "doi":
        kind = CROSSREF_TYPES.get(v["type"], "misc")
        f["author"] = authors(v["authors"])
        f["title"] = protect(v["title"])
        f["journal" if kind == "article" else "booktitle"] = esc(v["container"])
        f["year"] = v["year"]
        for a, b in (("volume", "volume"), ("issue", "number"), ("pages", "pages")):
            if v.get(a):
                f[b] = esc(v[a]).replace("-", "--")
        if v.get("article_number") and not v.get("pages"):
            f["pages"] = esc(v["article_number"])
        if v.get("publisher") and kind in ("book", "inproceedings"):
            f["publisher"] = esc(v["publisher"])
        f["doi"] = v["doi"]
    elif v["kind"] == "venue":
        kind = v.get("entrytype", "inproceedings")
        f.update(author=authors(v["authors"]), title=protect(v["title"]), year=v["year"])
        f["journal" if kind == "article" else "booktitle"] = esc(v["booktitle"])
    elif v["kind"] == "arxiv":
        kind = "misc"
        f.update(author=authors(v["authors"]), title=protect(v["title"]), year=v["year"],
                 howpublished=f"arXiv preprint arXiv:{v['arxiv']}")
    elif v["kind"] == "software":
        kind = "misc"
        f.update(author="{" + v["author_org"] + "}", title=protect(v["title"]), year=v["year"],
                 howpublished=r"\url{" + v["url"] + "}")
    else:
        return None
    if v.get("arxiv") and v["kind"] != "arxiv":
        f.update(eprint=v["arxiv"], archivePrefix="arXiv")
    body = ",\n".join(f"  {k} = {{{val}}}" for k, val in f.items())
    return f"@{kind}{{{key},\n{body}\n}}"


def main():
    refs = json.load(open(OUT / "refs_verified.json", encoding="utf-8"))
    cited = set()
    for p in (OUT / "text").glob("*.tex"):
        for m in re.finditer(r"\\cite[pt]?\{([^}]*)\}", p.read_text(encoding="utf-8")):
            cited |= {k.strip() for k in m.group(1).split(",")}
    entries, missing = [], sorted(k for k in cited if k not in refs or refs[k]["kind"] == "unverified")
    for k in sorted(cited - set(missing)):
        entries.append(entry(k, refs[k]))
    head = ("% Generated by make_bib.py from refs_verified.json -- every entry checked against its DOI, arXiv or\n"
            "% publisher record; do not edit by hand.\n\n")
    (OUT / "references.bib").write_text(head + "\n\n".join(entries) + "\n", encoding="utf-8")
    lines = ["# Citations: verification record", "",
             "Generated by make_bib.py. Each key cited in paper_out/text/*.tex, the record it was checked against, and the "
             "venue used in references.bib.", "",
             f"Cited but unverified (must be resolved before submission): {', '.join(missing) or 'none'}", "",
             "| Key | Venue | Year | Checked against |", "|---|---|---|---|"]
    for k in sorted(cited - set(missing)):
        v = refs[k]
        venue = v.get("container") or v.get("booktitle") or ("arXiv:" + v["arxiv"] if v["kind"] == "arxiv" else v.get("url"))
        src = v["source"] + (f" (doi:{v['doi']})" if v.get("doi") else "")
        lines.append(f"| `{k}` | {venue} | {v.get('year')} | {src} |")
    (OUT / "text" / "citations_needed.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(entries)} entries to {OUT / 'references.bib'}; cited but unverified: {missing or 'none'}")
    unused = sorted(k for k in refs if k not in cited)
    if unused:
        print("verified but not cited:", ", ".join(unused))


if __name__ == "__main__":
    main()
